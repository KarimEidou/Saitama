/* -------------------------------------------------------------------------- */
/* Cross-section evaluation                                                   */
/* -------------------------------------------------------------------------- */

/** Signed power: keeps the superellipse symmetric through the origin. */
function signPow(value: number, power: number): number {
  const a = Math.abs(value);
  const r = power === 1 ? a : Math.pow(a, power);
  return value < 0 ? -r : r;
}

/**
 * Evaluate a cross-section at ring parameter `t` in 0..1.
 *
 * t=0 is -axisB (the BACK of an upright body), t=0.25 is +axisA, t=0.5 is
 * +axisB (the FRONT), t=0.75 is -axisA. Keeping the seam at the back is what
 * puts the face in the middle of its atlas rectangle.
 */
export function evalRingPoint(shape: RingShape, t: number, out: THREE.Vector2): THREE.Vector2 {
  const angle = TAU * t - Math.PI / 2;
  const ca = Math.cos(angle);
  const sa = Math.sin(angle);
  const exponent = shape.exponent ?? 2;
  const power = 2 / exponent;

  let a = shape.radiusA * signPow(ca, power);
  let b = shape.radiusB * signPow(sa, power);

  if (b >= 0) {
    if (shape.frontScale !== undefined) b *= shape.frontScale;
  } else if (shape.backScale !== undefined) {
    b *= shape.backScale;
  }

  a += shape.offsetA ?? 0;
  b += shape.offsetB ?? 0;

  return out.set(a, b);
}

/* -------------------------------------------------------------------------- */
/* Analytic skinning                                                          */
/* -------------------------------------------------------------------------- */

/** Ramp from 0 to 1 across [edge - width, edge + width]. */
function ramp(s: number, edge: number, width: number): number {
  if (width <= 0) return s < edge ? 0 : 1;
  return smootherstep(edge - width, edge + width, s);
}

const EMPTY_SKIN: SkinWeight4 = { index: [0, 0, 0, 0], weight: [1, 0, 0, 0] };

/**
 * Collapse an arbitrary bone->weight map into exactly four normalised slots.
 *
 * Ordering is weight-descending with a bone-index tiebreak, so the same
 * anatomical position always produces the same slot layout — which is what
 * lets morph targets be generated by re-lofting a perturbed profile.
 */
export function packSkin(
  contributions: ReadonlyMap<number, number>,
  fallbackBone = 0
): SkinWeight4 {
  const entries: [number, number][] = [];
  for (const [bone, weight] of contributions) {
    if (weight > 1e-5) entries.push([bone, weight]);
  }
  if (entries.length === 0) {
    return { index: [fallbackBone, fallbackBone, fallbackBone, fallbackBone], weight: [1, 0, 0, 0] };
  }

  entries.sort((x, y) => (y[1] === x[1] ? x[0] - y[0] : y[1] - x[1]));
  const kept = entries.slice(0, 4);

  let total = 0;
  for (const [, w] of kept) total += w;

  const index: [number, number, number, number] = [
    kept[0]![0],
    kept[0]![0],
    kept[0]![0],
    kept[0]![0],
  ];
  const weight: [number, number, number, number] = [0, 0, 0, 0];
  for (let i = 0; i < kept.length; i++) {
    index[i] = kept[i]![0];
    weight[i] = kept[i]![1] / total;
  }

  // Kill residual float error on the dominant slot so the sum is exactly 1.
  const sum = weight[0] + weight[1] + weight[2] + weight[3];
  weight[0] += 1 - sum;

  return { index, weight };
}

/**
 * Evaluate a bone chain at parameter `s`.
 *
 * Each span owns the surface between its own start and end, crossfading with
 * its neighbour over a window centred on the shared joint. Because the two
 * ramps at a joint are exact complements, the pair already sums to 1 before
 * normalisation — normalisation only ever has to correct overlapping windows
 * on very short bones.
 */
export function evaluateChain(
  chain: SkinChain,
  s: number,
  boneIndex: Readonly<Record<BoneName, number>>
): SkinWeight4 {
  const spans = chain.spans;
  if (spans.length === 0) return EMPTY_SKIN;

  const contributions = new Map<number, number>();

  for (let i = 0; i < spans.length; i++) {
    const span = spans[i]!;
    const prev = i > 0 ? spans[i - 1] : undefined;

    const enter = prev === undefined ? 1 : ramp(s, span.start, prev.blend ?? 0);
    const leave = i === spans.length - 1 ? 1 : 1 - ramp(s, span.end, span.blend ?? 0);
    const membership = enter * leave;
    if (membership <= 1e-5) continue;

    const idx = boneIndex[span.bone];
    contributions.set(idx, (contributions.get(idx) ?? 0) + membership);
  }

  if (chain.bias !== undefined) {
    for (const bias of chain.bias) {
      const falloff = 1 - clamp01(Math.abs(s - bias.at) / Math.max(bias.range, 1e-6));
      const amount = bias.amount * smootherstep(0, 1, falloff);
      if (amount <= 1e-5) continue;
      const idx = boneIndex[bias.bone];
      contributions.set(idx, (contributions.get(idx) ?? 0) + amount);
    }
  }

  const fallback = boneIndex[spans[0]!.bone];
  return packSkin(contributions, fallback);
}

/** Linearly blend two influence sets and renormalise to four slots. */
export function blendSkin(a: SkinWeight4, b: SkinWeight4, t: number): SkinWeight4 {
  const contributions = new Map<number, number>();
  const add = (skin: SkinWeight4, scale: number): void => {
    for (let i = 0; i < 4; i++) {
      const w = skin.weight[i]! * scale;
      if (w <= 0) continue;
      const idx = skin.index[i]!;
      contributions.set(idx, (contributions.get(idx) ?? 0) + w);
    }
  };
  add(a, 1 - t);
  add(b, t);
  return packSkin(contributions, a.index[0]!);
}

/** A single bone at full weight. */
export function rigidSkin(bone: BoneName, boneIndex: Readonly<Record<BoneName, number>>): SkinWeight4 {
  const i = boneIndex[bone];
  return { index: [i, i, i, i], weight: [1, 0, 0, 0] };
}

