/**
 * LOFTING CORE
 *
 * Turns ordered cross-sections into skinned, UV'd, watertight triangles, and
 * evaluates the analytic skin weights that make the whole approach worthwhile.
 *
 * Three properties are load-bearing and every change here must preserve them:
 *
 *  1. WINDING. Ring parameter t always advances the same way relative to the
 *     sweep direction, and the ring frame always satisfies
 *     `cross(axisA, axisB) === axis`. Together those make the quad ordering
 *     `(i,k) (i,k+1) (i+1,k+1)` face outward for EVERY strand, however it is
 *     oriented. Tests assert positive signed volume per component, which is
 *     exactly a winding check.
 *
 *  2. WATERTIGHTNESS. The seam column is duplicated so u can reach 1.0, and
 *     flat caps duplicate their rim so the crease is hard. Duplicated
 *     vertices are bit-identical in position, so the surface is closed even
 *     though the index buffer is not welded. Manifold tests weld by position
 *     first — that is the correct way to test a UV-seamed mesh.
 *
 *  3. NORMALS. Averaged across position-welded vertices that share a smoothing
 *     group, so the UV seam does not show as a lighting crack, while flat caps
 *     and hard-surface panels keep genuine hard edges.
 */

