/** Quantisation used when welding positions for normals and manifold checks. */
const WELD_SCALE = 1e5;

/**
 * Append-only vertex/index accumulator.
 *
 * Plain number arrays rather than typed arrays: generation happens once at
 * load time and the counts are not known up front, so growth cost beats the
 * bookkeeping of resizing typed buffers.
 */
export class MeshBuilder {
  private readonly position: number[] = [];
  private readonly uv: number[] = [];
  private readonly color: number[] = [];
  private readonly skinIndex: number[] = [];
  private readonly skinWeight: number[] = [];
  private readonly smooth: number[] = [];
  private readonly index: number[] = [];
  private readonly regions: MeshRegionInfo[] = [];
  private open: { name: string; slot: MeshSlot; start: number } | undefined;

  get vertexCount(): number {
    return this.position.length / 3;
  }

  get triangleCount(): number {
    return this.index.length / 3;
  }

  beginRegion(name: string, slot: MeshSlot): void {
    if (this.open !== undefined) this.endRegion();
    this.open = { name, slot, start: this.index.length };
  }

  endRegion(): void {
    const open = this.open;
    if (open === undefined) return;
    const count = this.index.length - open.start;
    this.open = undefined;
    if (count === 0) return;
    this.regions.push({
      name: open.name,
      slot: open.slot,
      indexStart: open.start,
      indexCount: count,
      triangles: count / 3,
    });
  }

  addVertex(
    p: THREE.Vector3,
    u: number,
    v: number,
    color: THREE.Color,
    skin: SkinWeight4,
    smoothGroup: number
  ): number {
    const id = this.position.length / 3;
    this.position.push(p.x, p.y, p.z);
    this.uv.push(u, v);
    this.color.push(color.r, color.g, color.b);
    this.skinIndex.push(skin.index[0], skin.index[1], skin.index[2], skin.index[3]);
    this.skinWeight.push(skin.weight[0], skin.weight[1], skin.weight[2], skin.weight[3]);
    this.smooth.push(smoothGroup);
    return id;
  }

  addTriangle(a: number, b: number, c: number): void {
    this.index.push(a, b, c);
  }

  /** Two triangles across a quad, wound so `a -> b -> c -> d` faces outward. */
  addQuad(a: number, b: number, c: number, d: number): void {
    this.index.push(a, b, c, a, c, d);
  }

  /**
   * Smooth normals, welded by (quantised position, smoothing group).
   *
   * Face normals are accumulated unnormalised so they carry triangle area as
   * their magnitude; that weights large faces more than slivers and is what
   * keeps the shoulder from developing a lighting pinch where a dense ring
   * meets a sparse one.
   */
  private computeNormals(): Float32Array {
    const count = this.vertexCount;
    const normals = new Float32Array(count * 3);
    const groups = new Map<string, number[]>();

    for (let i = 0; i < count; i++) {
      const key =
        `${Math.round(this.position[i * 3]! * WELD_SCALE)}|` +
        `${Math.round(this.position[i * 3 + 1]! * WELD_SCALE)}|` +
        `${Math.round(this.position[i * 3 + 2]! * WELD_SCALE)}|${this.smooth[i]}`;
      const bucket = groups.get(key);
      if (bucket === undefined) groups.set(key, [i]);
      else bucket.push(i);
    }

    const accum = new Map<string, THREE.Vector3>();
    const owner = new Array<string>(count);
    for (const [key, members] of groups) {
      accum.set(key, new THREE.Vector3());
      for (const m of members) owner[m] = key;
    }

    const pa = new THREE.Vector3();
    const pb = new THREE.Vector3();
    const pc = new THREE.Vector3();
    const ab = new THREE.Vector3();
    const cb = new THREE.Vector3();
    const faceNormal = new THREE.Vector3();

    for (let t = 0; t < this.index.length; t += 3) {
      const ia = this.index[t]!;
      const ib = this.index[t + 1]!;
      const ic = this.index[t + 2]!;
      pa.fromArray(this.position, ia * 3);
      pb.fromArray(this.position, ib * 3);
      pc.fromArray(this.position, ic * 3);
      cb.subVectors(pc, pb);
      ab.subVectors(pa, pb);
      faceNormal.crossVectors(cb, ab);
      accum.get(owner[ia]!)!.add(faceNormal);
      accum.get(owner[ib]!)!.add(faceNormal);
      accum.get(owner[ic]!)!.add(faceNormal);
    }

    const n = new THREE.Vector3();
    for (let i = 0; i < count; i++) {
      n.copy(accum.get(owner[i]!)!);
      if (n.lengthSq() < 1e-20) n.set(0, 1, 0);
      else n.normalize();
      normals[i * 3] = n.x;
      normals[i * 3 + 1] = n.y;
      normals[i * 3 + 2] = n.z;
    }
    return normals;
  }

  /** Finalise into a skinning-ready `BufferGeometry`. */
  build(): { geometry: THREE.BufferGeometry; regions: readonly MeshRegionInfo[] } {
    this.endRegion();

    const geometry = new THREE.BufferGeometry();
    geometry.setAttribute('position', new THREE.Float32BufferAttribute(this.position, 3));
    geometry.setAttribute('normal', new THREE.BufferAttribute(this.computeNormals(), 3));
    geometry.setAttribute('uv', new THREE.Float32BufferAttribute(this.uv, 2));
    geometry.setAttribute('color', new THREE.Float32BufferAttribute(this.color, 3));
    geometry.setAttribute('skinIndex', new THREE.Uint16BufferAttribute(this.skinIndex, 4));
    geometry.setAttribute('skinWeight', new THREE.Float32BufferAttribute(this.skinWeight, 4));
    geometry.setIndex(this.index);

    // Merge adjacent regions that share a slot: three.js issues one draw call
    // per group, and a character has far more regions than materials.
    let cursor = -1;
    for (const region of this.regions) {
      const groups = geometry.groups;
      const last = cursor >= 0 ? groups[cursor] : undefined;
      if (last !== undefined && last.materialIndex === region.slot) {
        last.count += region.indexCount;
      } else {
        geometry.addGroup(region.indexStart, region.indexCount, region.slot);
        cursor = geometry.groups.length - 1;
      }
    }

    geometry.computeBoundingBox();
    geometry.computeBoundingSphere();
    return { geometry, regions: this.regions };
  }
}

