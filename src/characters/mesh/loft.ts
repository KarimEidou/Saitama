/** Sweep directions, one per ring: explicit, else a central difference. */
function ringAxes(rings: readonly Ring[]): THREE.Vector3[] {
  const out: THREE.Vector3[] = [];
  for (let i = 0; i < rings.length; i++) {
    const ring = rings[i]!;
    if (ring.axis !== undefined) {
      out.push(ring.axis.clone().normalize());
      continue;
    }
    const prev = rings[Math.max(0, i - 1)]!;
    const next = rings[Math.min(rings.length - 1, i + 1)]!;
    const axis = next.center.clone().sub(prev.center);
    if (axis.lengthSq() < 1e-12) axis.set(0, 1, 0);
    out.push(axis.normalize());
  }
  return out;
}

/**
 * Rotation-minimising frames along the sweep.
 *
 * Naively rebuilding the frame from a fixed up-vector makes the mesh spin
 * where the spline turns (visible as texture swirl and as twisted rings in the
 * ankle and cape). Parallel transport carries the previous frame through the
 * minimal rotation between consecutive tangents instead, so the surface only
 * twists where the geometry genuinely does.
 */
function ringFrames(
  axes: readonly THREE.Vector3[],
  hint: THREE.Vector3
): { a: THREE.Vector3; b: THREE.Vector3 }[] {
  const frames: { a: THREE.Vector3; b: THREE.Vector3 }[] = [];
  const q = new THREE.Quaternion();

  let a = hint.clone();
  a.addScaledVector(axes[0]!, -a.dot(axes[0]!));
  if (a.lengthSq() < 1e-10) {
    a = Math.abs(axes[0]!.y) < 0.9 ? new THREE.Vector3(0, 1, 0) : new THREE.Vector3(1, 0, 0);
    a.addScaledVector(axes[0]!, -a.dot(axes[0]!));
  }
  a.normalize();

  for (let i = 0; i < axes.length; i++) {
    if (i > 0) {
      q.setFromUnitVectors(axes[i - 1]!, axes[i]!);
      a = a.clone().applyQuaternion(q);
      a.addScaledVector(axes[i]!, -a.dot(axes[i]!));
      if (a.lengthSq() < 1e-10) a.set(axes[i]!.y, axes[i]!.z, axes[i]!.x);
      a.normalize();
    }
    frames.push({ a: a.clone(), b: new THREE.Vector3().crossVectors(axes[i]!, a) });
  }
  return frames;
}

const _p = new THREE.Vector3();
const _local = new THREE.Vector2();
const _uv: [number, number] = [0, 0];
const _axisA = new THREE.Vector3();
const _axisB = new THREE.Vector3();

/**
 * Height of a pole cap over a cross-section.
 *
 * The SMALLER semi-axis, not the mean: capping an ellipse at its mean radius
 * produces a cone on the narrow axis and a dent on the wide one. Bounding the
 * dome by the minor axis is the only choice that stays plausible for both a
 * near-circular limb end and a flat paddle like a fingertip.
 */
export function poleHeight(shape: RingShape): number {
  return Math.min(Math.abs(shape.radiusA), Math.abs(shape.radiusB)) * 0.92;
}

/**
 * Triangulate one strand into the builder.
 *
 * Returns the per-ring vertex id table so callers (garment shells, panels,
 * decals) can attach to exact surface positions rather than guessing.
 */
export function loftStrand(builder: MeshBuilder, strand: Strand): number[][] {
  const { rings, radialSegments: segments, uvRect } = strand;
  if (rings.length < 2) return [];

  const axes = ringAxes(rings);
  const frames = ringFrames(axes, strand.frameHint);
  const grid: number[][] = [];

  builder.beginRegion(strand.name, strand.slot);

  for (let i = 0; i < rings.length; i++) {
    const ring = rings[i]!;
    const frame = frames[i]!;
    _axisA.copy(frame.a);
    _axisB.copy(frame.b);
    if (ring.roll !== undefined && ring.roll !== 0) {
      _axisA.applyAxisAngle(axes[i]!, ring.roll);
      _axisB.applyAxisAngle(axes[i]!, ring.roll);
    }
    const color = ring.color ?? strand.color;

    const row: number[] = [];
    // segments + 1 columns: the last duplicates the first so u can reach 1.
    for (let k = 0; k <= segments; k++) {
      const t = k / segments;
      evalRingPoint(ring.shape, t === 1 ? 0 : t, _local);
      _p.copy(ring.center).addScaledVector(_axisA, _local.x).addScaledVector(_axisB, _local.y);
      packUV(uvRect, t, ring.v, _uv);
      row.push(builder.addVertex(_p, _uv[0], _uv[1], color, ring.skin, strand.smoothGroup));
    }
    grid.push(row);
  }

  for (let i = 0; i < rings.length - 1; i++) {
    const lo = grid[i]!;
    const hi = grid[i + 1]!;
    for (let k = 0; k < segments; k++) {
      builder.addQuad(lo[k]!, lo[k + 1]!, hi[k + 1]!, hi[k]!);
    }
  }

  capStrand(builder, strand, grid, axes, frames, true);
  capStrand(builder, strand, grid, axes, frames, false);

  builder.endRegion();
  return grid;
}

function capStrand(
  builder: MeshBuilder,
  strand: Strand,
  grid: readonly number[][],
  axes: readonly THREE.Vector3[],
  frames: readonly { a: THREE.Vector3; b: THREE.Vector3 }[],
  atStart: boolean
): void {
  const mode = atStart ? strand.capStart : strand.capEnd;
  if (mode === 'none') return;

  const i = atStart ? 0 : grid.length - 1;
  const ring = strand.rings[i]!;
  const row = grid[i]!;
  const segments = strand.radialSegments;
  const axis = axes[i]!;
  const outward = atStart ? -1 : 1;

  if (mode === 'pole') {
    // Reuse the rim vertices so the dome stays smooth-shaded, and push the
    // pole out by roughly the rim radius so the end reads as a hemisphere
    // rather than a cone.
    const explicit = atStart ? strand.poleStart : strand.poleEnd;
    _p.copy(ring.center).addScaledVector(axis, outward * (explicit ?? poleHeight(ring.shape)));
    packUV(strand.uvRect, 0.5, atStart ? Math.max(0, ring.v - 0.03) : Math.min(1, ring.v + 0.03), _uv);
    const pole = builder.addVertex(
      _p,
      _uv[0],
      _uv[1],
      ring.color ?? strand.color,
      ring.skin,
      strand.smoothGroup
    );
    for (let k = 0; k < segments; k++) {
      if (atStart) builder.addTriangle(row[k + 1]!, row[k]!, pole);
      else builder.addTriangle(row[k]!, row[k + 1]!, pole);
    }
    return;
  }

  // Flat cap: duplicate the rim into its own smoothing group so the silhouette
  // edge stays sharp, then fan to a centre vertex.
  const group = strand.smoothGroup + 0x4000 + (atStart ? 0 : 1);
  const frame = frames[i]!;
  const rim: number[] = [];
  for (let k = 0; k <= segments; k++) {
    const t = k / segments;
    evalRingPoint(ring.shape, t === 1 ? 0 : t, _local);
    _p.copy(ring.center).addScaledVector(frame.a, _local.x).addScaledVector(frame.b, _local.y);
    packUV(strand.uvRect, t, ring.v, _uv);
    rim.push(
      builder.addVertex(_p, _uv[0], _uv[1], ring.color ?? strand.color, ring.skin, group)
    );
  }
  _p.copy(ring.center);
  packUV(strand.uvRect, 0.5, ring.v, _uv);
  const hub = builder.addVertex(
    _p,
    _uv[0],
    _uv[1],
    ring.color ?? strand.color,
    ring.skin,
    group
  );
  for (let k = 0; k < segments; k++) {
    if (atStart) builder.addTriangle(rim[k + 1]!, rim[k]!, hub);
    else builder.addTriangle(rim[k]!, rim[k + 1]!, hub);
  }
}

/** Convenience: build a `Strand` with the fields most call sites share. */
export function makeStrand(
  name: string,
  rings: readonly Ring[],
  options: {
    readonly radialSegments: number;
    readonly uvRect: UVRect;
    readonly slot: MeshSlot;
    readonly color: THREE.Color;
    readonly frameHint: THREE.Vector3;
    readonly smoothGroup: number;
    readonly capStart?: import('./types').CapMode;
    readonly capEnd?: import('./types').CapMode;
    readonly poleStart?: number;
    readonly poleEnd?: number;
  }
): Strand {
  return {
    name,
    rings,
    radialSegments: options.radialSegments,
    capStart: options.capStart ?? 'pole',
    capEnd: options.capEnd ?? 'pole',
    uvRect: options.uvRect,
    slot: options.slot,
    color: options.color,
    frameHint: options.frameHint,
    smoothGroup: options.smoothGroup,
    poleStart: options.poleStart,
    poleEnd: options.poleEnd,
  };
}
