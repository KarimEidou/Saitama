/** Region colours baked into the vertex-colour attribute. */
export interface Palette {
  readonly skin: THREE.Color;
  readonly cloth: THREE.Color;
  readonly accent: THREE.Color;
  readonly hair: THREE.Color;
  readonly metal: THREE.Color;
  readonly vent: THREE.Color;
}

const DEFAULT_SKIN = 0xe8b48c;
const DEFAULT_CLOTH = 0x40587e;
const DEFAULT_ACCENT = 0x2a2d33;

/** Resolve a palette from the profile, with optional pins. */
export function resolvePalette(profile: BodyProfile, overrides?: Partial<Palette>): Palette {
  const base: Palette = {
    skin: new THREE.Color(profile.skinTone ?? DEFAULT_SKIN),
    cloth: new THREE.Color(profile.primaryColor ?? DEFAULT_CLOTH),
    accent: new THREE.Color(profile.secondaryColor ?? DEFAULT_ACCENT),
    hair: new THREE.Color(0x22190f),
    metal: new THREE.Color(0x9aa3ad),
    vent: new THREE.Color(0x14181d),
  };
  return overrides === undefined ? base : { ...base, ...overrides };
}

/* -------------------------------------------------------------------------- */
/* Costumes                                                                   */
/* -------------------------------------------------------------------------- */

/** Cloth thickness as a radial multiplier. */
const CLOTH_INFLATE = 1.035;
const TIGHT_INFLATE = 1.015;

/** Everyday clothes: shirt with short sleeves, trousers, shoes. */
export function casualCostume(palette: Palette): PaintFn {
  const shirt: Coat = { color: palette.cloth, inflate: CLOTH_INFLATE };
  const trousers: Coat = { color: palette.accent, inflate: CLOTH_INFLATE };
  const shoe: Coat = { color: palette.accent, inflate: TIGHT_INFLATE };
  const skin: Coat = { color: palette.skin };

  return (part, _key, at) => {
    switch (part) {
      case 'torso':
        if (at < 0.215) return trousers;
        if (at < 0.665) return shirt;
        return skin;
      case 'arm':
        return at < 0.5 ? shirt : skin;
      case 'leg':
        return at < 1.88 ? trousers : skin;
      case 'foot':
        return shoe;
      default:
        return skin;
    }
  };
}

/** A full-coverage bodysuit, the base for most hero costumes. */
export function bodysuitCostume(
  palette: Palette,
  options: {
    readonly gloveFrom?: number;
    readonly bootFrom?: number;
    readonly neckTo?: number;
  } = {}
): PaintFn {
  const suit: Coat = { color: palette.cloth, inflate: CLOTH_INFLATE };
  const trim: Coat = { color: palette.accent, inflate: TIGHT_INFLATE };
  const skin: Coat = { color: palette.skin };
  const gloveFrom = options.gloveFrom ?? 1.5;
  const bootFrom = options.bootFrom ?? 1.55;
  const neckTo = options.neckTo ?? 0.69;

  return (part, _key, at) => {
    switch (part) {
      case 'torso':
        return at < neckTo ? suit : skin;
      case 'arm':
        return at < gloveFrom ? suit : trim;
      case 'leg':
        return at < bootFrom ? suit : trim;
      case 'hand':
        return trim;
      case 'foot':
        return trim;
      default:
        return skin;
    }
  };
}

