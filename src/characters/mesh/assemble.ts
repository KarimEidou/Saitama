export interface HumanoidOptions {
  readonly lod?: LodLevel;
  /** Pin resolved shape axes, for named characters. */
  readonly shape?: ShapeOverrides;
  readonly palette?: Partial<Palette>;
  /** Costume paint. Defaults to `casualCostume`. */
  readonly paint?: PaintFn;
  readonly garments?: GarmentSpec;
  readonly hair?: HairSpec;
  readonly hardSurface?: HardSurfaceSpec;
  /** Morph targets to derive by re-lofting. */
  readonly morphTargets?: readonly MorphSpec[];
}

export interface HumanoidBuild {
  readonly geometry: THREE.BufferGeometry;
  readonly rig: HumanoidRig;
  readonly regions: readonly MeshRegionInfo[];
  readonly stats: HumanoidStats;
  readonly profile: BodyProfile;
  readonly palette: Palette;
  readonly shape: ShapeParams;
  /** Morph target names, in `geometry.morphAttributes.position` order. */
  readonly morphNames: readonly string[];
}

