/**
 * ASSEMBLY — profile in, skinned geometry out
 *
 * This is the only file that knows the whole character. It resolves the LOD
 * table, builds every strand, drapes the costume, lofts the lot into one
 * buffer and derives morph targets.
 *
 * ── ONE MESH, NOT TWELVE ──────────────────────────────────────────────────
 * Everything merges into a SINGLE indexed geometry with a single skeleton.
 * Region colour rides in a vertex-colour attribute and material slots ride in
 * `geometry.groups`, so a caller who passes one material gets one draw call
 * per character (groups are ignored by three.js unless the material is an
 * array), and a caller who wants metal to look like metal can pass an array
 * and pay for it deliberately. On a mid-tier phone rendering a street full of
 * civilians, that choice is the difference between shipping and not.
 *
 * ── MORPH TARGETS COME FROM RE-LOFTING ────────────────────────────────────
 * A morph target is generated by rebuilding the character with a perturbed
 * profile and subtracting positions. Topology depends only on the LOD and the
 * costume — never on the profile's scalars — so the two builds are guaranteed
 * vertex-for-vertex compatible. That is far more robust than sculpting deltas,
 * and it means any parameter the generator understands can become a morph.
 */

