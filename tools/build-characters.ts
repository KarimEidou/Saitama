interface GlbInput {
  readonly entry: RosterEntry;
  readonly builds: readonly { lod: LodLevel; build: HumanoidBuild }[];
  readonly albedo: Buffer;
  readonly orm: Buffer;
  readonly normal: Buffer;
  readonly emissive?: Buffer;
}

/**
 * Write one character as a self-contained, skinned GLB.
 *
 * The ORM packing is not a convention we invented — it is exactly glTF's:
 * `occlusionTexture` reads R, `metallicRoughnessTexture` reads G and B. So one
 * embedded image serves both slots and any glTF viewer shows the character
 * correctly without knowing anything about this project.
 */
async function writeGlb(input: GlbInput, file: string): Promise<number> {
  const doc = new Document();
  doc.createBuffer();
  const buffer = doc.getRoot().listBuffers()[0]!;
  const scene = doc.createScene(input.entry.name);

  const texture = (name: string, data: Buffer): ReturnType<Document['createTexture']> =>
    doc
      .createTexture(name)
      .setImage(new Uint8Array(data.buffer, data.byteOffset, data.byteLength))
      .setMimeType('image/png');

  // ONE ORM texture object serves both slots. Creating two would embed the
  // same PNG twice — glTF's occlusion and metallic-roughness textures are
  // allowed to share an image precisely because R and GB never collide.
  const ormTexture = texture('orm', input.orm);
  const material = doc
    .createMaterial(input.entry.name)
    .setBaseColorFactor([1, 1, 1, 1])
    .setBaseColorTexture(texture('albedo', input.albedo))
    .setMetallicFactor(1)
    .setRoughnessFactor(1)
    .setMetallicRoughnessTexture(ormTexture)
    .setOcclusionTexture(ormTexture)
    .setNormalTexture(texture('normal', input.normal))
    .setDoubleSided(false);
  if (input.emissive !== undefined) {
    material.setEmissiveFactor([1, 1, 1]).setEmissiveTexture(texture('emissive', input.emissive));
  }

  // One skeleton serves every LOD: the bones are identical, only the surface
  // changes. Built from LOD0's rig.
  const primary = input.builds[0]!.build;
  const bones = primary.rig.bones;
  const nodes = bones.map((bone) =>
    doc
      .createNode(bone.name)
      .setTranslation([bone.position.x, bone.position.y, bone.position.z])
      .setRotation([bone.quaternion.x, bone.quaternion.y, bone.quaternion.z, bone.quaternion.w])
      .setScale([bone.scale.x, bone.scale.y, bone.scale.z])
  );
  for (let i = 0; i < bones.length; i++) {
    const parent = bones[i]!.parent;
    const parentIndex = parent === null ? -1 : bones.indexOf(parent as THREE.Bone);
    if (parentIndex >= 0) nodes[parentIndex]!.addChild(nodes[i]!);
  }
  const rootIndex = bones.findIndex((bone) => !bones.includes(bone.parent as THREE.Bone));
  scene.addChild(nodes[Math.max(0, rootIndex)]!);

  const inverses = new Float32Array(bones.length * 16);
  primary.rig.skeleton.boneInverses.forEach((matrix, i) => {
    inverses.set(matrix.elements, i * 16);
  });
  const ibm = doc.createAccessor('ibm').setType('MAT4').setArray(inverses).setBuffer(buffer);

  const skin = doc
    .createSkin('rig')
    .setInverseBindMatrices(ibm)
    .setSkeleton(nodes[Math.max(0, rootIndex)]!);
  for (const node of nodes) skin.addJoint(node);

  for (const { lod, build } of input.builds) {
    const geometry = build.geometry;
    const accessor = (
      name: string,
      type: 'VEC2' | 'VEC3' | 'VEC4' | 'SCALAR',
      array: Float32Array | Uint16Array | Uint32Array
    ): Accessor => doc.createAccessor(name).setType(type).setArray(array).setBuffer(buffer);

    const position = geometry.getAttribute('position');
    const normal = geometry.getAttribute('normal');
    const uv = geometry.getAttribute('uv');
    const skinIndex = geometry.getAttribute('skinIndex');
    const skinWeight = geometry.getAttribute('skinWeight');
    const index = geometry.getIndex()!;

    const primitive = doc
      .createPrimitive()
      .setAttribute('POSITION', accessor('P', 'VEC3', new Float32Array(position.array)))
      .setAttribute('NORMAL', accessor('N', 'VEC3', new Float32Array(normal.array)))
      .setAttribute('TEXCOORD_0', accessor('UV', 'VEC2', new Float32Array(uv.array)))
      .setAttribute('JOINTS_0', accessor('J', 'VEC4', new Uint16Array(skinIndex.array)))
      .setAttribute('WEIGHTS_0', accessor('W', 'VEC4', new Float32Array(skinWeight.array)))
      .setIndices(accessor('I', 'SCALAR', new Uint32Array(index.array)))
      .setMaterial(material);

    const mesh = doc.createMesh(`${input.entry.name} LOD${lod}`).addPrimitive(primitive);
    const node = doc.createNode(`${input.entry.id}_LOD${lod}`).setMesh(mesh).setSkin(skin);
    scene.addChild(node);
  }

  const io = new NodeIO();
  const glb = await io.writeBinary(doc);
  await writeFile(file, glb);
  return glb.byteLength;
}

