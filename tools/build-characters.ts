/**
 * CHARACTER BAKER — roster in, shippable character assets out
 *
 *   npx tsx tools/build-characters.ts [--only saitama,genos] [--size 1024]
 *                                     [--no-ao] [--no-vat] [--no-glb]
 *
 * For every entry in `@/characters/roster` this writes, into
 * `public/assets/chr/<name>/` (gitignored, re-derivable):
 *
 *   albedo.<tier>.png   base colour, opaque RGB
 *   mask.<tier>.png     per-instance tint mask; crowd characters only
 *   orm.<tier>.png      AO (R) / roughness (G) / metalness (B)
 *   normal.<tier>.png   tangent-space normal
 *   emissive.<tier>.png only for characters that actually glow
 *   face.<tier>.png     four expression tiles, stacked, straight alpha
 *   model.glb           LOD0 + LOD1, skinned, textures embedded
 *   vat.bin / vat.json  animation texture for the instanced crowd
 *
 * and, into the committed `tools/manifest/characters.json`, a DETERMINISTIC
 * declaration of what those files are: ids, roles, colour spaces, tiers,
 * triangle counts, threat tiers, and the licence of every CC0 texture the bake
 * consumed. No timestamps and no build hashes go in the committed file — it
 * describes the roster, not one particular run, so re-running the baker
 * produces no diff unless the roster actually changed. Any flag that changes
 * what a run produces (`--only`, `--size`, `--no-glb`, `--no-vat`) therefore
 * suppresses that write entirely rather than baking a run-specific fact — or
 * an outright lie about files this run did not write — into a tracked file.
 *
 * ── WHERE THE PIXELS COME FROM ────────────────────────────────────────────
 * Two sources, and the split is deliberate:
 *
 *   CC0 PHOTOGRAPHY  the Poly Haven maps the texture pipeline already fetched.
 *                    Metal, vents, joints and painted shells sample the real
 *                    4k albedo/normal/ARM. Genos' forearms are literally
 *                    `metal_plate` — its ARM map drives roughness per texel.
 *   SYNTHESIS        weave, twill, canvas, leather grain, pores, hair strands,
 *                    scales and carapace cells are generated. The CC0 library
 *                    is a CITY library and contains no cloth; tiling brick onto
 *                    a jumpsuit would look worse than no map at all.
 *
 * Faces are rasterised from SVG through `sharp`, twice: once at the atlas patch
 * size so the GLB is self-contained, and once at full tile resolution for the
 * expression strip the material samples at runtime.
 *
 * NOTHING here downloads a character asset. Every mesh is generated by
 * `@/characters/mesh`; every texture is either synthesised or CC0 with a
 * recorded author.
 */

