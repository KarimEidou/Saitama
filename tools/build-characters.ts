/**
 * Rasterise an SVG into the atlas' orientation.
 *
 * `.flip()` is the whole reason this helper exists: face art is authored the
 * way a person draws a face — brow at the top — while the atlas stores row 0
 * at v = 0, which puts the brow at the BOTTOM. Flipping once here keeps the
 * authoring readable and every consumer downstream flip-free.
 */
async function rasteriseFace(svg: string, width: number, height: number): Promise<FacePatch> {
  const { data } = await sharp(Buffer.from(svg), { density: 96 })
    .resize(width, height, { fit: 'fill' })
    .flip()
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  return {
    rgba: new Uint8Array(data.buffer, data.byteOffset, data.byteLength),
    width,
    height,
  };
}

