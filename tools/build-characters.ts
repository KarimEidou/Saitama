interface ManifestAttribution {
  readonly license: string;
  readonly author: string;
  readonly sourceUrl: string;
  readonly attributionUrl?: string;
  readonly year?: number;
}

/**
 * Credit every CC0 texture the bake consumed.
 *
 * A missing entry is fatal, not skippable: `entries[].cc0Textures` is written
 * from the roster and would still name the id, so dropping it here produces a
 * committed manifest that lists a texture it cannot credit — and
 * `tools/attribution.ts` audits the credit block, so the gap would read as a
 * pass. The manifest must never claim a CC0 texture with no author behind it.
 */
async function cc0Attribution(
  ids: readonly string[]
): Promise<Record<string, ManifestAttribution>> {
  const manifest = await loadTextureManifest();
  const out: Record<string, ManifestAttribution> = {};
  for (const id of ids) {
    const entry = manifest.get(id);
    if (entry === undefined) {
      throw new Error(
        `CC0 detail material "${id}" is used by the roster but is not in ` +
          `tools/manifest/textures.json — it cannot be credited`
      );
    }
    out[id] = entry.attribution;
  }
  return out;
}

/**
 * The committed manifest.
 *
 * Deterministic by construction: no timestamps, no build hashes, keys in a
 * fixed order. Re-running the baker on an unchanged roster produces no diff,
 * which is what makes this file reviewable.
 */
async function writeSourceManifest(reports: readonly CharacterReport[]): Promise<void> {
  const roster = new Map(listRoster().map((entry) => [entry.id, entry]));
  const allCc0 = [...new Set(reports.flatMap((report) => report.cc0))].sort();
  const attribution = await cc0Attribution(allCc0);

  const entries = reports.map((report) => {
    const entry = roster.get(report.id)!;
    const spec = materialSpecFor(entry);
    // Declared from what the bake WROTE, not from `entryGlows(entry)`. The two
    // are computed from different data — the predicate reads the raw
    // `entry.surfaces` overrides, the atlas reads the resolved style set — so a
    // character can glow without overriding anything, and the manifest would
    // then under-declare two PNGs that are on disk and in the GLB.
    const roles = [
      'albedo',
      'orm',
      'normal',
      ...(report.emissive ? ['emissive'] : []),
      ...(entry.crowd === true ? ['mask'] : []),
    ];

    return {
      id: entry.id,
      kind: 'character',
      name: entry.name,
      role: entry.kind,
      threat: entry.threat,
      targetFormat: 'glb',
      skeleton: 'mixamo',
      height: report.height,
      triangles: report.triangles.lod0,
      attribution: PROJECT_ATTRIBUTION,
      sourceUrl: PROJECT_ATTRIBUTION.sourceUrl,
      generator: 'tools/build-characters.ts',
      directory: characterDir(entry),
      model: 'model.glb',
      lodLevels: GLB_LODS.map((lod) => ({
        level: lod,
        file: `${characterDir(entry)}/model.glb`,
        triangles: report.triangles[`lod${lod}`] ?? 0,
      })),
      crowdLod: { level: 2, triangles: report.triangles.lod2 ?? 0, delivery: 'vat' },
      materialKeys: [materialAssetId(entry)],
      material: { id: materialAssetId(entry), kind: 'material', spec },
      textures: roles.map((role) => ({
        id: mapAssetId(entry, role as 'albedo'),
        role: role === 'albedo' ? 'albedo' : role,
        colorSpace: role === 'albedo' || role === 'emissive' ? 'srgb' : 'linear',
        targetFormat: 'png',
        tileable: false,
        files: TIERS.map((tier) => ({
          tier,
          file: `${characterDir(entry)}/${mapFileName(role as 'albedo', tier)}`,
          // The roster's tier edge, never `report.atlasSize` — that is this
          // run's `--size`, and writing it here would contradict `atlas.tiers`
          // below, which is built from the same constant.
          size: TIER_SIZE[tier]!,
        })),
      })),
      face: {
        id: mapAssetId(entry, 'face'),
        colorSpace: 'srgb',
        expressions: EXPRESSIONS,
        tile: report.faceTile,
        files: TIERS.map((tier) => ({
          tier,
          file: `${characterDir(entry)}/face.${tier}.png`,
        })),
      },
      vat: report.vat === undefined ? undefined : { file: `${characterDir(entry)}/vat.bin` },
      surfaceClasses: report.classes,
      cc0Textures: report.cc0,
    };
  });

  const manifest = {
    version: 1,
    kind: 'character',
    generator: 'tools/build-characters.ts',
    description:
      'Procedural character roster. Every mesh is generated by @/characters/mesh and every ' +
      'texture is either synthesised by @/characters/roster or a CC0 Poly Haven map listed in ' +
      'cc0Textures. No third-party character asset is used, downloaded or referenced anywhere ' +
      'in this roster.',
    atlas: {
      tiers: Object.fromEntries(TIERS.map((tier) => [tier, TIER_SIZE[tier]])),
      layout: 'row 0 = v 0; textures bind with flipY=false',
      packing: 'albedo RGB + crowd tint mask in A; ORM = AO(R)/roughness(G)/metalness(B)',
    },
    thirdPartyCharacterAssets: 0,
    cc0Attribution: attribution,
    entries,
  };

  // Formatted with the project's own Prettier config so the committed file is
  // byte-identical to what `npm run format` would produce — otherwise every
  // bake and every format pass would fight over the same file.
  const prettierOptions = (await resolveConfig(MANIFEST_FILE)) ?? {};
  const json = await format(JSON.stringify(manifest), { ...prettierOptions, parser: 'json' });
  await writeFile(MANIFEST_FILE, json);
}

/** The build report, written next to the binaries and gitignored. */
async function writeRuntimeIndex(reports: readonly CharacterReport[]): Promise<void> {
  const dir = path.join(OUT_ROOT, 'chr');
  await mkdir(dir, { recursive: true });
  await writeFile(
    path.join(dir, 'characters.runtime.json'),
    `${JSON.stringify({ generatedRoot: 'chr', characters: reports }, null, 2)}\n`
  );
}

/* -------------------------------------------------------------------------- */
/* Main                                                                       */
/* -------------------------------------------------------------------------- */

async function main(): Promise<void> {
  const options = parseArgs(process.argv.slice(2));
  const roster = listRoster().filter((entry) => matches(entry, options.only));
  if (roster.length === 0) {
    console.error('no roster entries matched');
    process.exit(1);
  }

  console.log(
    `characters · ${roster.length} entries · atlas ${options.size} · ` +
      `ao=${options.ao} glb=${options.glb} vat=${options.vat}`
  );

  const reports: CharacterReport[] = [];
  for (const entry of roster) {
    process.stdout.write(`  ${entry.id.padEnd(20)} `);
    const report = await buildCharacter(entry, options);
    reports.push(report);
    const mb = (report.gpuBytes.high / (1024 * 1024)).toFixed(1);
    console.log(
      `${report.triangles.lod0} tris · coverage ${(report.coverage * 100).toFixed(1)}% · ` +
        `${mb} MB GPU · ${report.seconds}s`
    );
  }

  await writeRuntimeIndex(reports);
  const describes = describesRoster(options);
  if (options.manifest && describes.ok) await writeSourceManifest(reports);
  else if (options.manifest) {
    console.log(`  · tools/manifest/characters.json not rewritten: ${describes.reason}`);
  }

  const totalHigh = reports.reduce((sum, report) => sum + report.gpuBytes.high, 0);
  const totalMobile = reports.reduce((sum, report) => sum + report.gpuBytes.mobile, 0);
  console.log(
    `\ndone · ${reports.length} characters · GPU high ${(totalHigh / 1048576).toFixed(1)} MB · ` +
      `mobile ${(totalMobile / 1048576).toFixed(1)} MB`
  );
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
