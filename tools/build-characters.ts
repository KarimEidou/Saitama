/* Occlusion                                                                  */
/* -------------------------------------------------------------------------- */

/**
 * Ray-traced ambient occlusion over the character itself.
 *
 * Fourteen cosine-weighted rays per sample, capped at 34 cm, so the signal is
 * CONTACT occlusion — the shadow under a chin, inside an armpit, between the
 * cape and the back — not a global bent-normal. That is the part a stylised
 * character actually needs: it grounds the costume against the body, which is
 * the single thing flat vertex colour cannot do.
 */
function makeOcclusion(build: HumanoidBuild): OcclusionSampler {
  const geometry = build.geometry.clone();
  geometry.deleteAttribute('color');
  geometry.deleteAttribute('skinIndex');
  geometry.deleteAttribute('skinWeight');
  const bvh = new MeshBVH(geometry);

  const rng = createRng(0x5a17a).derive('ao');
  const directions: [number, number, number][] = [];
  for (let i = 0; i < AO_RAYS; i++) {
    // Cosine-weighted hemisphere around +Z, stratified by a golden-angle spiral
    // so fourteen rays cover the dome evenly instead of clumping.
    const u = (i + 0.5) / AO_RAYS;
    const r = Math.sqrt(u);
    const phi = i * 2.399963 + rng.range(0, 0.4);
    directions.push([r * Math.cos(phi), r * Math.sin(phi), Math.sqrt(Math.max(0, 1 - u))]);
  }

  const ray = new THREE.Ray();
  const tangent = new THREE.Vector3();
  const bitangent = new THREE.Vector3();
  const normal = new THREE.Vector3();
  const helper = new THREE.Vector3();

  return (positions, normals, count) => {
    const out = new Float32Array(count);
    for (let i = 0; i < count; i++) {
      const o = i * 3;
      normal.set(normals[o]!, normals[o + 1]!, normals[o + 2]!);
      if (normal.lengthSq() < 0.5) {
        out[i] = 1;
        continue;
      }
      helper.set(0, 0, 1);
      if (Math.abs(normal.z) > 0.9) helper.set(1, 0, 0);
      tangent.crossVectors(helper, normal).normalize();
      bitangent.crossVectors(normal, tangent);

      let open = 0;
      for (const [dx, dy, dz] of directions) {
        ray.origin
          .set(positions[o]!, positions[o + 1]!, positions[o + 2]!)
          .addScaledVector(normal, 1.5e-3);
        ray.direction
          .set(0, 0, 0)
          .addScaledVector(tangent, dx)
          .addScaledVector(bitangent, dy)
          .addScaledVector(normal, dz)
          .normalize();
        const hit = bvh.raycastFirst(ray, THREE.DoubleSide, 0, AO_RADIUS);
        if (hit === null) open += 1;
        else open += Math.min(1, hit.distance / AO_RADIUS) * 0.55;
      }
      out[i] = open / AO_RAYS;
    }
    return out;
  };
}

