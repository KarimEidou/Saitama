let textureEntries: Map<string, TextureEntry> | undefined;

async function loadTextureManifest(): Promise<Map<string, TextureEntry>> {
  if (textureEntries !== undefined) return textureEntries;
  const raw = JSON.parse(await readFile(TEXTURE_MANIFEST, 'utf8')) as {
    entries: readonly TextureEntry[];
  };
  textureEntries = new Map(raw.entries.map((entry) => [entry.id, entry]));
  return textureEntries;
}

const tileCache = new Map<string, DetailTile | undefined>();

/**
 * Decode one CC0 material into a small tiling detail source.
 *
 * The 4k source is 10-15 MB of JPEG; the bake needs a few hundred texels of
 * grain, not a photograph. Downsampling to 512 up front makes every subsequent
 * lookup a cache hit in L2 and makes the whole bake CPU-bound on the rasteriser
 * rather than on image decode.
 */
async function loadDetailTile(id: string): Promise<DetailTile | undefined> {
  const cached = tileCache.get(id);
  if (cached !== undefined || tileCache.has(id)) return cached;

  const manifest = await loadTextureManifest();
  const entry = manifest.get(id);
  if (entry === undefined) {
    console.warn(`  ! detail material "${id}" is not in the texture manifest — skipping`);
    tileCache.set(id, undefined);
    return undefined;
  }

  const pick = (role: string): string | undefined =>
    entry.files.find((file) => file.role === role)?.path;

  const albedoPath = pick('albedo');
  const normalPath = pick('normal');
  const armPath = pick('orm') ?? pick('arm');
  if (albedoPath === undefined || normalPath === undefined || armPath === undefined) {
    console.warn(`  ! detail material "${id}" is missing a map — skipping`);
    tileCache.set(id, undefined);
    return undefined;
  }

  // Every consumer below indexes this buffer as tightly packed 8-bit RGB. A
  // greyscale, CMYK or 16-bit source would come back with a different stride,
  // and the reads that ran off the end would be `undefined` — the `!` is
  // compile-time only — which turns `meanRough` into NaN and, downstream, every
  // texel of the surface class into roughness 0. So ask for sRGB and then check
  // what actually arrived rather than assume it.
  const expectedBytes = DETAIL_TILE_SIZE * DETAIL_TILE_SIZE * 3;
  const read = async (relative: string): Promise<Uint8Array> => {
    const { data, info } = await sharp(path.join(SOURCE_DIR, relative))
      .resize(DETAIL_TILE_SIZE, DETAIL_TILE_SIZE, { fit: 'fill', kernel: 'lanczos3' })
      .toColourspace('srgb')
      .removeAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });
    if (info.channels !== 3 || data.byteLength !== expectedBytes) {
      throw new Error(
        `${relative} decoded to ${info.channels} channels / ${data.byteLength} bytes, ` +
          `expected 3 / ${expectedBytes}`
      );
    }
    return new Uint8Array(data.buffer, data.byteOffset, data.byteLength);
  };

  let albedo: Uint8Array;
  let normal: Uint8Array;
  let arm: Uint8Array;
  try {
    [albedo, normal, arm] = await Promise.all([read(albedoPath), read(normalPath), read(armPath)]);
  } catch (error) {
    console.warn(`  ! detail material "${id}" failed to decode: ${(error as Error).message}`);
    tileCache.set(id, undefined);
    return undefined;
  }

  let luma = 0;
  let rough = 0;
  const texels = DETAIL_TILE_SIZE * DETAIL_TILE_SIZE;
  for (let i = 0; i < texels; i++) {
    const o = i * 3;
    const r = srgbToLinear(albedo[o]! / 255);
    const g = srgbToLinear(albedo[o + 1]! / 255);
    const b = srgbToLinear(albedo[o + 2]! / 255);
    luma += 0.2126 * r + 0.7152 * g + 0.0722 * b;
    rough += arm[o + 1]! / 255;
  }

  const tile: DetailTile = {
    id,
    size: DETAIL_TILE_SIZE,
    albedo,
    normal,
    arm,
    meanLuma: Math.max(luma / texels, 1e-3),
    meanRough: Math.max(rough / texels, 1e-3),
  };
  tileCache.set(id, tile);
  return tile;
}

function srgbToLinear(value: number): number {
  return value <= 0.04045 ? value / 12.92 : Math.pow((value + 0.055) / 1.055, 2.4);
}

